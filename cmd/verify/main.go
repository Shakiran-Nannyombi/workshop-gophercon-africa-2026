// Command verify collects every "verify" note in /data into a Markdown checklist.
//
//	go run ./cmd/verify > VERIFY.md
package main

import (
	"encoding/json"
	"fmt"
	"io/fs"
	"log"
	"os"
	"path"
	"sort"
	"strings"
)

type item struct{ where, note string }

func main() {
	log.SetFlags(0)
	log.SetPrefix("verify: ")
	fsys := os.DirFS("data")
	files, err := fs.Glob(fsys, "*.json")
	if err != nil {
		log.Fatal(err)
	}
	sort.Strings(files)

	var site struct {
		LastReviewed string `json:"lastReviewed"`
	}
	if b, err := fs.ReadFile(fsys, "site.json"); err == nil {
		_ = json.Unmarshal(b, &site)
	}

	var out strings.Builder
	total := 0
	for _, f := range files {
		b, err := fs.ReadFile(fsys, f)
		if err != nil {
			log.Fatal(err)
		}
		var v any
		if err := json.Unmarshal(b, &v); err != nil {
			log.Fatalf("%s: %v", f, err)
		}
		var items []item
		walk(v, nil, &items)
		if len(items) == 0 {
			continue
		}
		total += len(items)
		fmt.Fprintf(&out, "\n## %s (%d)\n\n", path.Join("data", f), len(items))
		for _, it := range items {
			fmt.Fprintf(&out, "- [ ] **%s**: %s\n", it.where, oneLine(it.note))
		}
	}

	fmt.Println("# VERIFY")
	fmt.Println()
	fmt.Println("Every value in `/data` marked `\"verify\"`, generated by `make verify`. Do not edit by hand:")
	fmt.Println("fix the fact in the JSON, delete its `verify` note, and run `make verify` again.")
	fmt.Println()
	fmt.Printf("%d notes. Content last reviewed %s.\n", total, site.LastReviewed)
	fmt.Print(out.String())
}

// walk records each "verify" string with a readable trail of names leading to it.
func walk(v any, trail []string, items *[]item) {
	switch t := v.(type) {
	case map[string]any:
		here := trail
		if l := label(t); l != "" {
			here = append(append([]string{}, trail...), l)
		}
		if n, ok := t["verify"].(string); ok && n != "" {
			w := strings.Join(here, " › ")
			if w == "" {
				w = "(file)"
			}
			*items = append(*items, item{w, n})
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			if k == "verify" {
				continue
			}
			child := here
			if _, isMap := t[k].(map[string]any); isMap {
				child = append(append([]string{}, here...), k)
			}
			walk(t[k], child, items)
		}
	case []any:
		for _, e := range t {
			walk(e, trail, items)
		}
	}
}

func label(m map[string]any) string {
	for _, k := range []string{"name", "term", "title", "item", "code", "slug", "label", "from"} {
		if s, ok := m[k].(string); ok && s != "" {
			if k == "from" {
				if to, ok := m["to"].(string); ok {
					return s + " → " + to
				}
			}
			return s
		}
		if n, ok := m[k].(float64); ok && k == "code" {
			return fmt.Sprint(n)
		}
	}
	if n, ok := m["value"].(float64); ok {
		return fmt.Sprint(n)
	}
	return ""
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
