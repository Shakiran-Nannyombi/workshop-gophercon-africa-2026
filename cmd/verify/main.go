// Command verify collects every "verify" note in /data into a Markdown
// checklist: go run ./cmd/verify > VERIFY.md (or make verify).
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"time"
)

// item is one value in the data that still needs checking.
type item struct {
	Path, Label, Text string
}

// labelKeys are tried in order to give an item a human name.
var labelKeys = []string{"name", "slug", "item", "title", "number", "term", "value", "code"}

// manual lists checks that have no "verify" field in the data.
var manual = []string{
	"glossary/faq/sources have no verify field: eTA details and exemptions; M-Pesa options for visitors; Rwanda is UTC+2; emergency numbers 999/112; Sheng \"soo\" = 100 and \"thao\" = 1,000; Metro Trains booking URL.",
	"Nairobi's area appears as ~696 km² in nairobi.json but 704 in counties.json; reconcile with KNBS.",
	"Exchange rates in data/site.json are placeholders.",
	"The East Africa and county map borders are simplified geoBoundaries/Natural Earth shapes; check they are fit for purpose.",
}

func main() {
	dir := flag.String("data", "data", "directory holding the content JSON")
	flag.Parse()
	if err := run(os.Stdout, *dir, time.Now()); err != nil {
		fmt.Fprintln(os.Stderr, "verify:", err)
		os.Exit(1)
	}
}

func run(w io.Writer, dir string, now time.Time) error {
	files, err := filepath.Glob(filepath.Join(dir, "*.json"))
	if err != nil {
		return err
	}
	geo, err := filepath.Glob(filepath.Join(dir, "geo", "*.json"))
	if err != nil {
		return err
	}
	sort.Strings(files)
	sort.Strings(geo)

	type section struct {
		Name  string
		Items []item
	}
	var sections []section
	total := 0
	for _, f := range files {
		v, err := decode(f)
		if err != nil {
			return err
		}
		var items []item
		walk(v, "", "", &items)
		if len(items) > 0 {
			sections = append(sections, section{rel(dir, f), items})
			total += len(items)
		}
	}
	var credits []string
	for _, f := range geo {
		v, err := decode(f)
		if err != nil {
			return err
		}
		m, _ := v.(map[string]any)
		src, _ := m["source"].(string)
		lic, _ := m["license"].(string)
		if src != "" || lic != "" {
			credits = append(credits, fmt.Sprintf("- `%s`: %s (licence: %s)", rel(dir, f), or(src, "no source"), or(lic, "no licence")))
		}
	}

	p := func(format string, a ...any) { fmt.Fprintf(w, format, a...) }
	p("# Karibu Guide: things to verify\n\n")
	p("Generated by `make verify` (`go run ./cmd/verify > VERIFY.md`) from every `\"verify\"` note in `/data`. Don't edit this file by hand: fix the data, delete its `verify` note, then regenerate.\n\n")
	p("Generated on %s. %d items flagged in data across %d files, plus %d manual checks.\n\n", now.Format("2006-01-02"), total, len(sections), len(manual))
	for _, s := range sections {
		p("## %s (%d)\n\n", s.Name, len(s.Items))
		for _, it := range s.Items {
			label := ""
			if it.Label != "" {
				label = " (" + it.Label + ")"
			}
			p("- [ ] `%s`%s: %s\n", it.Path, label, oneLine(it.Text))
		}
		p("\n")
	}
	if len(credits) > 0 {
		p("## Map data credits (data/geo)\n\nShape files are not scanned for notes; these are their top-level credits, shown on /about.\n\n")
		for _, c := range credits {
			p("%s\n", c)
		}
		p("\n")
	}
	p("## Not flagged in data (manual checks)\n\n")
	for _, m := range manual {
		p("- [ ] %s\n", m)
	}
	return nil
}

func decode(path string) (any, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var v any
	if err := json.Unmarshal(b, &v); err != nil {
		return nil, fmt.Errorf("parsing %s: %w", path, err)
	}
	return v, nil
}

// walk records every non-empty "verify" string under v, labelled by the nearest named object.
func walk(v any, path, label string, out *[]item) {
	switch t := v.(type) {
	case map[string]any:
		if l := labelOf(t); l != "" && path != "" {
			label = l
		}
		if s, ok := t["verify"].(string); ok && strings.TrimSpace(s) != "" {
			*out = append(*out, item{Path: orDash(path), Label: label, Text: s})
		}
		keys := make([]string, 0, len(t))
		for k := range t {
			if k != "verify" {
				keys = append(keys, k)
			}
		}
		sort.Strings(keys)
		for _, k := range keys {
			walk(t[k], join(path, k), label, out)
		}
	case []any:
		for i, e := range t {
			walk(e, path+"["+strconv.Itoa(i)+"]", label, out)
		}
	}
}

func labelOf(m map[string]any) string {
	for _, k := range labelKeys {
		switch x := m[k].(type) {
		case string:
			if x != "" && k == "number" {
				return "number " + x
			} else if x != "" {
				return x
			}
		case float64:
			return k + " " + strconv.FormatFloat(x, 'f', -1, 64)
		}
	}
	return ""
}

func join(path, key string) string {
	if path == "" {
		return key
	}
	return path + "." + key
}

func rel(dir, f string) string {
	r, err := filepath.Rel(filepath.Dir(dir), f)
	if err != nil {
		return f
	}
	return filepath.ToSlash(r)
}

func orDash(s string) string { return or(s, "(top level)") }

func or(s, fallback string) string {
	if s == "" {
		return fallback
	}
	return s
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
